#!/usr/bin/env python3
"""Renders all of Void Slime's in-game art into app/src/main/res/drawable-nodpi and writes ui/Art.kt, the map
from art names to drawables (so the resource shrinker keeps them and the code can look them up by name).

Run from anywhere:  python3 art/gen_art.py [only-these-prefixes...]
Previews (PNG) and contact sheets land in art/out (git-ignored).
"""
import os
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from artlib import PREVIEW, RES, ROOT, S, canvas, save  # noqa: E402
import icons  # noqa: E402

KOTLIN = os.path.join(ROOT, "app/src/main/java/dev/m4s4t0/voidslime/ui/Art.kt")


def sheet(names, out, cell=96, cols=12):
    rows = (len(names) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cell, rows * (cell + 14)), (24, 18, 44, 255))
    d = ImageDraw.Draw(img)
    for i, n in enumerate(names):
        p = os.path.join(PREVIEW, n + ".png")
        if not os.path.exists(p):
            continue
        im = Image.open(p).convert("RGBA")
        im.thumbnail((cell, cell))
        x, y = (i % cols) * cell, (i // cols) * (cell + 14)
        img.alpha_composite(im, (x + (cell - im.width) // 2, y))
        d.text((x + 2, y + cell), n[3:][:15], fill=(200, 200, 220, 255))
    img.save(os.path.join(PREVIEW, out))


def main():
    only = sys.argv[1:]
    import items, people, stickers  # noqa: F401  (they add to icons.ICONS)
    names = []
    for g in [icons.ICONS]:
        for name, fn in g.items():
            res = "ic_" + name
            names.append(res)
            if only and not any(name.startswith(o) for o in only):
                continue
            surf, ctx = canvas()
            fn(ctx)
            save(surf, res)
    if not only or "world" in only:
        import worlds
        worlds.main()
    shown = [n for n in names if not only or any(n[3:].startswith(o) for o in only)]
    sheet(shown, "sheet_icons.png")
    write_kotlin(names)


def write_kotlin(names):
    allres = sorted(f[:-5] for f in os.listdir(RES) if f.endswith(".webp"))
    lines = [
        "package dev.m4s4t0.voidslime.ui",
        "",
        "import dev.m4s4t0.voidslime.R",
        "",
        "/** Every piece of game art by name. Generated by art/gen_art.py, do not edit. */",
        "object Art {",
        "    val ids: Map<String, Int> = mapOf(",
    ]
    for r in allres:
        key = r[3:] if r.startswith("ic_") else r
        lines.append(f'        "{key}" to R.drawable.{r},')
    lines += ["    )", "}", ""]
    open(KOTLIN, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
